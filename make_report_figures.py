# 27 - what an EMPTY room actually looks like, quiet vs loud
# --------------------------------------------------------------------------
def fig_empty_room_character(out_dir, quiet_session, loud_session):
    """Only the empty-labelled frames, concatenated.

    Figure 23 shows the two classes overlapping in a loud session but not why.
    The reason is visible only in time order: the loud sessions are not
    uniformly noisy, they alternate between a quiet state and a disturbed one.
    That distinction matters, because the noise-floor metric averages, and an
    average over a bursty signal describes neither state.
    """
    fig, axes = plt.subplots(2, 1, figsize=(7.2, 4.6), sharey=True)

    for ax, session, tag in ((axes[0], quiet_session, "quiet"),
                             (axes[1], loud_session, "loud")):
        amps, labels, _ = session_arrays(session)
        e = frame_energy(amps)
        emp = e[labels[1:] == 0]
        t = np.arange(len(emp)) / 10.0

        ax.plot(t, emp, color=C_ACCENT, linewidth=0.55)
        ax.axhline(emp.mean(), color=C_MOVING, linestyle="--", linewidth=1.1)
        ax.axhline(np.median(emp), color=C_EMPTY, linestyle="--", linewidth=1.1)
        ax.set_xlim(0, t[-1])
        ax.set_ylabel("motion energy")
        ax.set_title(
            f"{session}  ({tag}):  mean {emp.mean():.2f}   "
            f"median {np.median(emp):.2f}   "
            f"{(emp > 5).mean() * 100:.0f}% of frames above 5",
            fontsize=9, pad=6, loc="left")
    axes[1].set_xlabel("time within the empty blocks (s)")

    handles = [plt.Line2D([], [], color=C_MOVING, linestyle="--"),
               plt.Line2D([], [], color=C_EMPTY, linestyle="--")]
    axes[0].legend(handles, ["mean", "median"], fontsize=8, ncol=2,
                   loc="upper right")

    fig.suptitle("An empty room is not uniformly quiet: the loud sessions burst",
                 fontsize=10, y=0.99)
    fig.tight_layout(rect=(0, 0, 1, 0.96))
    return save(fig, out_dir, "27_empty_room_character.png")


