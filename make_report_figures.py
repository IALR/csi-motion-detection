def build_combined_pdf(fig_dir, out_path):
    """Assemble every numbered PNG in `fig_dir` into one A4 figure book.

    Titles are derived from the file names rather than kept in a lookup table,
    so this cannot fall out of step with whatever full_model_report.py happens
    to emit."""
    names = sorted(f for f in os.listdir(fig_dir)
                   if f.lower().endswith(".png") and f[:2].isdigit())
    if not names:
        print("  no PNGs found; skipping combined PDF")
        return None

    with PdfPages(out_path) as pdf:
        fig = plt.figure(figsize=(8.27, 11.69))
        fig.text(0.5, 0.62, "Wi-Fi CSI Motion Detection", ha="center",
                 fontsize=22, fontweight="bold")
        fig.text(0.5, 0.575, "Complete figure set", ha="center",
                 fontsize=13, color="#55585f")
        fig.text(0.5, 0.53, f"{len(names)} figures", ha="center",
                 fontsize=10, color="#8b8e95")
        pdf.savefig(fig, facecolor="white")
        plt.close(fig)

        for n in names:
            num, _, rest = n[:-4].partition("_")
            title = f"{num}.  {rest.replace('_', ' ').capitalize()}"
            img = mpimg.imread(os.path.join(fig_dir, n))
            h, w = img.shape[0], img.shape[1]

            fig = plt.figure(figsize=(8.27, 11.69))
            # Fit the image inside the printable area while preserving aspect.
            avail_w, avail_h = 0.86, 0.78
            scale = min(avail_w / 1.0, avail_h / (h / w) if w else avail_h)
            iw, ih = scale, scale * (h / w)
            ax = fig.add_axes([(1 - iw) / 2, 0.10, iw, ih])
            ax.imshow(img)
            ax.axis("off")
            fig.text(0.5, 0.93, title, ha="center", fontsize=13,
                     fontweight="bold")
            pdf.savefig(fig, facecolor="white")
            plt.close(fig)

    print("  wrote", out_path, f"({len(names)} figures)")
    return out_path


