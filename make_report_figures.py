# 25 - noise floor vs held-out accuracy
# --------------------------------------------------------------------------
def fig_noise_vs_accuracy(out_dir, sessions, fold_csv):
    if not os.path.exists(fold_csv):
        print(f"  SKIPPED 25: {fold_csv} not found. Run full_model_report.py first.")
        return None
    folds = pd.read_csv(fold_csv).set_index("held_out_session")["test_accuracy"]

    xs, ys, names, cols = [], [], [], []
    for s in sessions:
        if s not in folds.index:
            continue
        amps, labels, _ = session_arrays(s)
        n = noise_floor(amps, labels)
        level, _, _ = assess_noise_floor(n)
        xs.append(n)
        ys.append(folds[s] * 100)
        names.append(s.replace("_data", ""))
        cols.append({"quiet": C_EMPTY, "moderate": C_WARN, "loud": C_MOVING}[level])

    fig, ax = plt.subplots(figsize=(7.2, 3.6))
    ax.axvspan(0, NOISE_REL_QUIET, color=C_EMPTY, alpha=0.06)
    ax.axvspan(NOISE_REL_QUIET, NOISE_REL_LOUD, color=C_WARN, alpha=0.06)
    ax.axvspan(NOISE_REL_LOUD, max(xs) * 1.14, color=C_MOVING, alpha=0.06)
    ax.scatter(xs, ys, c=cols, s=46, zorder=3, edgecolor="white", linewidth=0.8)

    # Place each label clear of its neighbours. With ten sessions and several
    # near-identical noise floors, a fixed offset overlaps: part_2 and part_3
    # printed on top of each other before this.
    order = np.argsort(xs)
    placed = []
    for i in order:
        x, y = xs[i], ys[i]
        for dx, dy, ha in ((7, -3, "left"), (7, 5, "left"), (-7, -3, "right"),
                           (7, -11, "left"), (-7, 5, "right")):
            # reject an offset whose anchor sits close to one already used
            cand = (x + dx * 0.0006, y + dy * 0.12)
            if all(abs(cand[0] - p[0]) > 0.008 or abs(cand[1] - p[1]) > 0.9
                   for p in placed):
                break
        placed.append(cand)
        ax.annotate(names[i], (x, y), textcoords="offset points",
                    xytext=(dx, dy), ha=ha, fontsize=7, color="#55585f")

    ax.set_xlabel("empty-room noise floor")
    ax.set_ylabel("held-out accuracy (%)")
    ax.set_xlim(0, max(xs) * 1.14)
    ax.set_ylim(min(ys) - 3.2, max(ys) + 1.6)
    ax.set_title("Held-out accuracy against measured noise floor", pad=7)

    # The honest caption is the point of this figure: the two loudest sessions
    # differ by ten points, so the floor is a risk indicator, not a forecast.
    # Anchored bottom-LEFT, which is empty - the low-accuracy points are all on
    # the right, where this text used to collide with them.
    r = np.corrcoef(xs, ys)[0, 1]
    ax.text(0.015, 0.04, f"Pearson r = {r:.2f}   (n = {len(xs)})",
            transform=ax.transAxes, ha="left", fontsize=8, color="#55585f")
    return save(fig, out_dir, "25_noise_floor_vs_accuracy.png")


