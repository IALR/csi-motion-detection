# 23 - class separation in a quiet room vs a loud one
# --------------------------------------------------------------------------
def fig_separation(out_dir, quiet_session, loud_session):
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.0), sharey=True)

    for ax, session in ((axes[0], quiet_session), (axes[1], loud_session)):
        amps, labels, _ = session_arrays(session)
        e = frame_energy(amps)
        lab = labels[1:]
        emp, mov = e[lab == 0], e[lab == 2]
        n = noise_floor(amps, labels)
        level, _, _ = assess_noise_floor(n)
        sep = mov.mean() / emp.mean()

        bins = np.linspace(0, np.percentile(e, 99.5), 55)
        ax.hist(emp, bins=bins, color=C_EMPTY, alpha=0.55, label="empty", density=True)
        ax.hist(mov, bins=bins, color=C_MOVING, alpha=0.55, label="moving", density=True)
        ax.axvline(emp.mean(), color=C_EMPTY, linestyle="--", linewidth=1.2)
        ax.axvline(mov.mean(), color=C_MOVING, linestyle="--", linewidth=1.2)
        ax.set_title(f"{session}\nnoise floor {n:.3f} ({level}),  "
                     f"separation {sep:.2f}$\\times$", fontsize=9, pad=7)
        ax.set_xlabel("motion energy per frame")
    axes[0].set_ylabel("density")
    axes[0].legend(fontsize=8)

    fig.suptitle("Why a loud room is hard: the two classes stop being separable",
                 fontsize=10, y=1.03)
    return save(fig, out_dir, "23_class_separation_quiet_vs_loud.png")


