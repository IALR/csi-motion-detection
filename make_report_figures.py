# shared loading helpers
# --------------------------------------------------------------------------
def session_arrays(folder):
    """Return (amps, labels, active_idx) for one session, settling dropped."""
    df = load_session(folder)
    cols = amp_columns(df)
    amps = df[cols].to_numpy(dtype=float)
    labels = df["label"].to_numpy()
    # The ~20 structurally dead guard-band subcarriers sit at exactly zero for
    # the whole recording. They are excluded from every figure: they would draw
    # as a permanent black stripe and would deflate any amplitude average.
    active = np.where(amps.mean(axis=0) > 0)[0]
    return amps, labels, active


def frame_energy(amps):
    """Mean absolute frame-to-frame amplitude change; length len(amps)-1."""
    return np.abs(np.diff(amps, axis=0)).mean(axis=1)


def noise_floor(amps, labels):
    """Scale-free empty-room noise floor, as csi_common defines it: jitter as a
    fraction of received amplitude, over active subcarriers only."""
    e = frame_energy(amps)
    lab = labels[1:]
    empty_e = e[lab == 0].mean() if (lab == 0).any() else np.nan
    empty_cols = amps[labels == 0].mean(axis=0)
    scale = empty_cols[empty_cols > 0].mean() if (empty_cols > 0).any() else np.nan
    return empty_e / scale if scale else np.nan


def short_name(session):
    """part_3_data -> P3, room2_part_1_data -> R2-1. Built from the trailing
    index rather than by string replacement, which previously turned
    room2_part_1_data into the malformed 'R2-_1'."""
    stem = session.replace("_data", "")
    idx = stem.rsplit("_", 1)[-1]
    return f"R2-{idx}" if stem.startswith("room2") else f"P{idx}"


def longest_block(labels, value):
    """Index range of the longest contiguous run of `value`."""
    best = (0, 0)
    start = None
    for i, v in enumerate(labels):
        if v == value and start is None:
            start = i
        elif v != value and start is not None:
            if i - start > best[1] - best[0]:
                best = (start, i)
            start = None
    if start is not None and len(labels) - start > best[1] - best[0]:
        best = (start, len(labels))
    return best


