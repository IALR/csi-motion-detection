"""
Project-specific report figures, computed from the real recorded sessions.

full_model_report.py already produces the ~20 standard classifier diagnostics
(confusion matrices, ROC/PR, learning and validation curves, feature
importance). This script produces the figures that are specific to THIS
project's findings and that a generic classifier report cannot know to draw:

    21  waterfall, empty vs moving          the raw signal, side by side
    22  motion energy across a transition   what the model actually keys on
    23  class separation, quiet vs loud     WHY a loud room is hard
    24  noise floor per session             the environment, graded
    25  noise floor vs held-out accuracy    the project's signature finding
    26  feature importance by family        which of the 5 families carries it

Nothing here is hand-typed: every number is recomputed from the session CSVs,
the saved model, or per_fold_results.csv as written by full_model_report.py.
Figures 25 needs those fold results, so run that script first:

    python full_model_report.py --model csi_model.joblib --sessions <all ten>
    python make_report_figures.py

Output: 300 dpi PNGs, sized for a single column of an A4 report.
"""

