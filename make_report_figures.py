# 24 - noise floor per session
# --------------------------------------------------------------------------
def fig_noise_per_session(out_dir, sessions):
    rows = []
    for s in sessions:
        amps, labels, _ = session_arrays(s)
        n = noise_floor(amps, labels)
        level, _, _ = assess_noise_floor(n)
        rows.append((s, n, level))
    rows.sort(key=lambda r: r[1])

    names = [short_name(r[0]) for r in rows]
    vals = [r[1] for r in rows]
    cols = {"quiet": C_EMPTY, "moderate": C_WARN, "loud": C_MOVING}
    bars = [cols[r[2]] for r in rows]

    fig, ax = plt.subplots(figsize=(7.2, 3.0))
    ax.bar(names, vals, color=bars, width=0.62)
    ax.axhline(NOISE_REL_QUIET, color=C_EMPTY, linestyle="--", linewidth=1)
    ax.axhline(NOISE_REL_LOUD, color=C_MOVING, linestyle="--", linewidth=1)
    # Anchored at the LEFT, where the bars are shortest, so the threshold
    # captions cannot land on top of the tall loud-session bars.
    ax.text(-0.45, NOISE_REL_QUIET + 0.005, f"quiet threshold {NOISE_REL_QUIET}",
            va="bottom", ha="left", fontsize=7.5, color=C_EMPTY)
    ax.text(-0.45, NOISE_REL_LOUD + 0.005, f"loud threshold {NOISE_REL_LOUD}",
            va="bottom", ha="left", fontsize=7.5, color=C_MOVING)
    for i, v in enumerate(vals):
        ax.text(i, v + 0.004, f"{v:.3f}", ha="center", fontsize=7)

    ax.set_ylabel("empty-room noise floor\n(jitter / mean amplitude)")
    ax.set_title("Measured noise floor of every recording session", pad=7)
    ax.set_ylim(0, max(vals) * 1.18)
    ax.set_xlim(-0.6, len(names) - 0.4)
    ax.tick_params(axis="x", labelsize=8)
    return save(fig, out_dir, "24_noise_floor_per_session.png")


