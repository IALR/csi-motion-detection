# Set by main() while a PdfPages is open. Held at module level rather than
# threaded through all six figure functions, which would add a parameter to
# each purely so that save() can reach it.
_PDF = None


def save(fig, out_dir, name):
    """Write the figure as a 300 dpi PNG and, if a PDF is open, add it as a
    page there too. The page is written from the live figure rather than by
    re-importing the PNG, so text and axes stay vector."""
    path = os.path.join(out_dir, name)
    fig.savefig(path, dpi=DPI, bbox_inches="tight", facecolor="white")
    if _PDF is not None:
        _PDF.savefig(fig, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    print("  wrote", path)
    return path


