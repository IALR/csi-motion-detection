# 26 - feature importance grouped by family
# --------------------------------------------------------------------------
def fig_importance_by_family(out_dir, model_path):
    bundle = joblib.load(model_path)
    imp = bundle["model"].feature_importances_
    names = bundle.get("feature_names") or feature_names(bundle["amp_columns"])
    n_amp = len(bundle["amp_columns"])

    # The five families, in the order calibrate_features concatenates them.
    # Short two-line labels: the full family names ("per-subcarrier mean
    # delta") overran their tick spacing and printed on top of each other.
    groups = [
        ("subcarrier\nmean delta", slice(0, n_amp), n_amp),
        ("subcarrier\nstd ratio", slice(n_amp, 2 * n_amp), n_amp),
        ("motion\nenergy", slice(2 * n_amp, 2 * n_amp + 2), 2),
        ("RSSI", slice(2 * n_amp + 2, 2 * n_amp + 4), 2),
        ("order-\ninvariant", slice(2 * n_amp + 4, len(names)), len(names) - (2 * n_amp + 4)),
    ]

    total = [imp[g[1]].sum() * 100 for g in groups]
    per_feat = [t / g[2] for t, g in zip(total, groups)]
    labels = [g[0] for g in groups]
    counts = [g[2] for g in groups]

    fig, axes = plt.subplots(1, 2, figsize=(7.6, 3.4))
    axes[0].bar(labels, total, color=C_ACCENT, width=0.6)
    axes[0].set_ylabel("total importance (%)")
    axes[0].set_title("Importance summed over each family", fontsize=9, pad=6)
    for i, (v, c) in enumerate(zip(total, counts)):
        axes[0].text(i, v + 0.7, f"{v:.1f}%\n({c} feat.)", ha="center", fontsize=7)
    axes[0].set_ylim(0, max(total) * 1.28)

    axes[1].bar(labels, per_feat, color=C_WARN, width=0.6)
    axes[1].set_ylabel("importance per feature (%)")
    axes[1].set_title("Importance per individual feature", fontsize=9, pad=6)
    for i, v in enumerate(per_feat):
        axes[1].text(i, v + max(per_feat) * 0.03, f"{v:.2f}%", ha="center", fontsize=7)
    axes[1].set_ylim(0, max(per_feat) * 1.25)

    for ax in axes:
        ax.tick_params(axis="x", labelsize=7)

    fig.suptitle("Where the model's discriminative power sits", fontsize=10, y=1.03)
    fig.subplots_adjust(wspace=0.32)
    return save(fig, out_dir, "26_feature_importance_by_family.png")


