# 21 - waterfall, empty vs moving
# --------------------------------------------------------------------------
def fig_waterfall(out_dir, session, n_frames=150):
    amps, labels, active = session_arrays(session)
    e_lo, e_hi = longest_block(labels, 0)
    m_lo, m_hi = longest_block(labels, 2)

    empty = amps[e_lo:e_lo + n_frames][:, active]
    moving = amps[m_lo:m_lo + n_frames][:, active]
    n = min(len(empty), len(moving))
    empty, moving = empty[:n], moving[:n]

    # One shared colour scale, or the two panels would not be comparable -
    # which is the entire point of the figure.
    both = np.concatenate([empty, moving])
    vmin, vmax = np.percentile(both, 2), np.percentile(both, 98)

    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.4), sharey=True)
    for ax, data, title, colour in (
            (axes[0], empty, "Room empty", C_EMPTY),
            (axes[1], moving, "Person moving", C_MOVING)):
        im = ax.imshow(data, aspect="auto", origin="upper", cmap=CSI_CMAP,
                       vmin=vmin, vmax=vmax, interpolation="nearest")
        ax.set_title(title, color=colour, fontweight="bold", pad=7)
        ax.set_xlabel("active subcarrier index")
        ax.grid(False)
    axes[0].set_ylabel("time (frames, newest at bottom)")

    cb = fig.colorbar(im, ax=axes, fraction=0.035, pad=0.02)
    cb.set_label("CSI amplitude", fontsize=8)
    cb.ax.tick_params(labelsize=7)

    fig.suptitle(f"Raw CSI amplitude over time  ({session}, {n} frames each)",
                 fontsize=10, y=1.01)
    return save(fig, out_dir, "21_waterfall_empty_vs_moving.png")


# --------------------------------------------------------------------------
# 22 - motion energy across a real empty -> moving transition
# --------------------------------------------------------------------------
def fig_energy_transition(out_dir, session):
    amps, labels, _ = session_arrays(session)
    e = frame_energy(amps)
    lab = labels[1:]

    fig, ax = plt.subplots(figsize=(7.2, 2.9))
    t = np.arange(len(e)) / 10.0  # 10 frames per second

    # Shade the ground-truth blocks, so the reader can see that the trace
    # changes at the labelled boundaries rather than being told that it does.
    start, cur = 0, lab[0]
    for i in range(1, len(lab) + 1):
        if i == len(lab) or lab[i] != cur:
            ax.axvspan(t[start], t[i - 1],
                       color=C_MOVING if cur == 2 else C_EMPTY,
                       alpha=0.10, linewidth=0)
            if i < len(lab):
                start, cur = i, lab[i]
    ax.plot(t, e, color=C_ACCENT, linewidth=0.9)

    ax.set_xlabel("time (s)")
    ax.set_ylabel("motion energy\n(mean |$\\Delta$ amplitude| per frame)")
    ax.set_xlim(t[0], t[-1])
    ax.set_ylim(bottom=0)
    ax.set_title(f"Motion energy across the labelled blocks of {session}",
                 pad=7)

    handles = [plt.Rectangle((0, 0), 1, 1, color=C_EMPTY, alpha=0.25),
               plt.Rectangle((0, 0), 1, 1, color=C_MOVING, alpha=0.25)]
    # Upper LEFT: the empty block sits near zero, so that corner is the only
    # part of the plot guaranteed to be free of data.
    ax.legend(handles, ["labelled EMPTY", "labelled MOVING"],
              loc="upper left", fontsize=8, ncol=2)
    return save(fig, out_dir, "22_motion_energy_transition.png")


